import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { format } from 'prettier';

execFileSync(
  process.execPath,
  ['node_modules/@custom-elements-manifest/analyzer/cem.js', 'analyze'],
  {
    stdio: 'inherit',
  },
);
const manifest = JSON.parse(await readFile('dist/custom-elements.json', 'utf8'));
for (const module of manifest.modules) {
  const source = await readFile(module.path, 'utf8');
  for (const declaration of module.declarations ?? []) {
    const hidden = new Set(
      (declaration.members ?? [])
        .filter((member) => member.privacy === 'private' || member.privacy === 'protected')
        .map((member) => member.name),
    );
    declaration.attributes = (declaration.attributes ?? []).filter(
      (attribute) => !hidden.has(attribute.fieldName),
    );
    declaration.members = (declaration.members ?? []).filter((member) => !hidden.has(member.name));
    declaration.events = (declaration.events ?? []).filter(
      (event) =>
        !(
          event.name === 'name' &&
          (event.inheritedFrom?.name === 'TerminalElement' ||
            declaration.name === 'TerminalElement')
        ),
    );
    for (const match of source.matchAll(/this\.emit\(['"]([^'"]+)['"]/g)) {
      if (!declaration.events.some((event) => event.name === match[1]))
        declaration.events.push({ name: match[1], type: { text: 'CustomEvent<unknown>' } });
    }
  }
}
const elements = manifest.modules.flatMap((module) =>
  (module.declarations ?? [])
    .filter((declaration) => declaration.tagName)
    .map((declaration) => ({
      ...declaration,
      path: module.path.replace(/^src\//, '').replace(/\.ts$/, '.js'),
    })),
);
// Resolve module references against the published package, rather than unpublished sources.
const rewrite = (value) => {
  if (!value || typeof value !== 'object') return;
  for (const [key, child] of Object.entries(value)) {
    if (
      (key === 'path' || key === 'module') &&
      typeof child === 'string' &&
      child.startsWith('src/')
    ) {
      value[key] = child.replace(/^src\//, 'dist/').replace(/\.ts$/, '.js');
    } else rewrite(child);
  }
};
rewrite(manifest);
await writeFile('dist/custom-elements.json', JSON.stringify(manifest, null, 2) + '\n');
await writeFile(
  'dist/catalog.json',
  JSON.stringify(
    elements.map(({ name, tagName, path }) => ({ name, tagName, path })),
    null,
    2,
  ) + '\n',
);
await writeFile(
  'dist/vscode.html-custom-data.json',
  JSON.stringify(
    {
      version: 1.1,
      tags: elements.map((element) => ({
        name: element.tagName,
        description: element.description ?? '',
        attributes: (element.attributes ?? []).map((attribute) => ({
          name: attribute.name,
          description: attribute.description ?? attribute.type?.text ?? '',
        })),
      })),
    },
    null,
    2,
  ) + '\n',
);

await mkdir('src/adapters/react', { recursive: true });
const generated =
  '// Generated by scripts/metadata.mjs. Edit components and rerun npm run metadata.';
const react = [generated];
for (const element of elements) {
  const events = new Set(['input', 'change', ...(element.events ?? []).map((event) => event.name)]);
  // The base class emit helper is not recognized as dispatchEvent by the analyzer.
  const source = await readFile(`src/${element.path.replace(/\.js$/, '.ts')}`, 'utf8');
  for (const match of source.matchAll(/this\.emit\(['"]([^'"]+)['"]/g)) events.add(match[1]);
  const entries = [...events].map((event) => {
    const prop =
      'on' +
      event
        .split('-')
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');
    return `${prop}: '${event}' as EventName<${event === 'input' || event === 'change' ? 'Event' : 'CustomEvent<unknown>'}>`;
  });
  const module = element.tagName.slice(2);
  const wrapper = [
    generated,
    "import * as React from 'react';",
    "import { createComponent, type EventName } from '@lit/react';",
    `import { ${element.name} as ${element.name}Element } from '../../${element.path.replace(/\.js$/, '')}';`,
    `export const ${element.name} = createComponent({ react: React, tagName: '${element.tagName}', elementClass: ${element.name}Element, events: { ${entries.join(', ')} } });`,
  ];
  await writeFile(
    `src/adapters/react/${module}.ts`,
    await format(wrapper.join('\n'), { parser: 'typescript', singleQuote: true, printWidth: 100 }),
  );
  react.push(`export { ${element.name} } from './react/${module}';`);
}
await writeFile(
  'src/adapters/react.ts',
  await format(react.join('\n'), { parser: 'typescript', singleQuote: true, printWidth: 100 }),
);
console.log(
  `Generated manifest, editor data, catalog, and React wrappers for ${elements.length} elements.`,
);
