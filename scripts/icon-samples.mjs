// Build-time selection keeps complete provider catalogs out of demo and library bundles.
import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';
const selected = {};
for (const [prefix, names] of Object.entries({
  bi: ['house', 'heart'],
  tabler: ['terminal-2', 'rocket'],
  heroicons: ['home', 'magnifying-glass'],
  'material-symbols': ['home', 'settings'],
})) {
  const set = JSON.parse(await readFile(`node_modules/@iconify-json/${prefix}/icons.json`, 'utf8'));
  selected[prefix] = {
    prefix,
    width: set.width,
    height: set.height,
    icons: Object.fromEntries(
      names.map((name) => {
        if (!set.icons[name]) throw new Error(`Missing ${prefix}:${name}`);
        return [name, set.icons[name]];
      }),
    ),
  };
}
await writeFile(
  'demo/icon-subsets.ts',
  await format(
    `// Generated by scripts/icon-samples.mjs from pinned dev dependencies. See docs/icons.md for licenses.\nexport const iconSubsets = ${JSON.stringify(selected)};\n`,
    { parser: 'typescript', singleQuote: true, printWidth: 100 },
  ),
);
